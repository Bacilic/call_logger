// Τι κάνει η εφαρμογή όταν χαθεί η πρόσβαση στη βάση **ενώ τρέχει**.
//
// Το πραγματικό σενάριο: η βάση ζει σε δικτυακό φάκελο, η εφαρμογή είναι ήδη
// ανοιχτή, και η σύνδεση προς τον φάκελο κόβεται — τα Windows ξαναζητούν
// διαπιστευτήρια. Η εφαρμογή δεν παγώνει· οι οθόνες «φορτώνουν» για πάντα.
//
// **Η προσομοίωση:** μια βάση που δέχεται ερωτήματα και δεν απαντά ποτέ. Δεν
// χρειάζεται δίκτυο, δεν χρειάζεται διακομιστής — μόνο ένα future που δεν
// ολοκληρώνεται, ακριβώς όπως ένα ερώτημα προς άφταστο δικτυακό αρχείο.
//
//   flutter test test/core/database/unreachable_database_test.dart

import 'dart:async';

import 'package:call_logger/core/database/calls_lansweeper_repository.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:sqflite_common/sqlite_api.dart';

/// Βάση που δέχεται τα πάντα και δεν απαντά σε τίποτα.
///
/// Το [noSuchMethod] πιάνει **κάθε** μέθοδο του `Database` χωρίς να χρειαστεί
/// να γραφτεί μία προς μία: όλες επιστρέφουν future που δεν ολοκληρώνεται.
/// Αυτό είναι ακριβώς η συμπεριφορά ενός ερωτήματος προς δικτυακό αρχείο που
/// έχει πάψει να είναι προσβάσιμο.
class UnreachableDatabase implements Database {
  @override
  dynamic noSuchMethod(Invocation invocation) => Completer<Never>().future;
}

void main() {
  group('Βάση που έπαψε να απαντά', () {
    test(
      'η ανάγνωση δεν ολοκληρώνεται ΠΟΤΕ — ούτε με σφάλμα, ούτε με άδειο',
      () async {
        // Αυτό ΕΙΝΑΙ το σφάλμα, όχι η επιθυμητή συμπεριφορά: η οθόνη που
        // περιμένει αυτή την απάντηση μένει στο «φορτώνει» για πάντα.
        final repo = CallsLansweeperRepository(UnreachableDatabase());

        // Μετράει και η επιτυχία και το σφάλμα: το ζητούμενο είναι να
        // ΤΕΛΕΙΩΣΕΙ η αναμονή, με οποιαδήποτε έκβαση.
        var settled = false;
        unawaited(
          repo
              .maxNumericLansweeperTicketId()
              .then<void>((_) {}, onError: (_, _) {})
              .whenComplete(() => settled = true),
        );

        // Πέντε δευτερόλεπτα πραγματικού χρόνου είναι υπεραρκετά: ο χειριστής
        // βλέπει τον κύκλο να γυρίζει πολύ περισσότερο.
        await Future<void>.delayed(const Duration(seconds: 5));

        expect(
          settled,
          isTrue,
          reason:
              'Η κλήση προς μη προσβάσιμη βάση δεν τελείωσε μέσα σε 5 '
              'δευτερόλεπτα. Χωρίς όριο χρόνου, η οθόνη φορτώνει για πάντα '
              'και ο χειριστής δεν μαθαίνει ποτέ τι έγινε.',
        );
      },
      timeout: const Timeout(Duration(seconds: 20)),
      skip: 'Ζωντανό σφάλμα: δεν υπάρχει ακόμη όριο χρόνου στα ερωτήματα.',
      // ΕΝΕΡΓΟΠΟΙΗΣΕ ΤΟ μόλις μπει όριο χρόνου στα ερωτήματα της βάσης.
      //
      // Το τεστ είναι γραμμένο και επαληθευμένο: τρέχει κόκκινο σήμερα, με
      // ακριβώς το μήνυμα που περιγράφει το σφάλμα. Μένει σημειωμένο ώστε η
      // σουίτα να μην έχει μόνιμα κόκκινο — όχι επειδή το σφάλμα έκλεισε.
    );
  });
}
