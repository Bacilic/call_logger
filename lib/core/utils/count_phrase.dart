/// Διαλέγει την πρόταση που ταιριάζει στο πλήθος: [one] για ακριβώς ένα,
/// [many] για κάθε άλλο πλήθος (και το μηδέν: «0 κατηγορίες»).
///
/// Δέχεται **ολόκληρη πρόταση** για κάθε μορφή, όχι μόνο το ουσιαστικό. Στα
/// ελληνικά με το πλήθος συμφωνούν και το ρήμα και η μετοχή — «Σημειώθηκε ως
/// διαγραμμένη 1 κατηγορία» / «Σημειώθηκαν ως διαγραμμένες 3 κατηγορίες» —
/// οπότε μια πρόταση που αλλάζει μόνο το ουσιαστικό αφήνει τις υπόλοιπες
/// λέξεις στον λάθος αριθμό.
String byCount(int count, {required String one, required String many}) =>
    count == 1 ? one : many;
