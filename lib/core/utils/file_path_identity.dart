/// Μία απάντηση στο «δείχνουν οι δύο διαδρομές στο ίδιο αρχείο;» για όλη την
/// εφαρμογή.
///
/// **Γιατί ένα σημείο.** Το ερώτημα έμοιαζε τόσο απλό που ο καθένας το έγραψε
/// μόνος του: μετρήθηκαν **επτά** υλοποιήσεις και **τρία** ακόμη αντίγραφα
/// χωρίς όνομα, με πέντε διαφορετικές συμπεριφορές. Στα οκτώ ζεύγη δοκιμής
/// συμφωνούσαν μόνο στα δύο. Όταν το ίδιο ερώτημα έχει πέντε απαντήσεις, η
/// σωστή είναι θέμα τύχης — και εδώ το ερώτημα κρίνει αν θα αντικατασταθεί ή
/// θα μετακινηθεί αρχείο βάσης.
///
/// **Τι καλύπτει:** κενά στις άκρες, ανάποδες και κανονικές καθέτους, περιττά
/// `.` και `..`, διπλούς διαχωριστές, πεζά/κεφαλαία στα Windows, και δικτυακές
/// διαδρομές (UNC) γραμμένες με οποιαδήποτε από τις δύο καθέτους.
///
/// **Τι ΔΕΝ κάνει: δεν μετατρέπει σχετική διαδρομή σε απόλυτη.** Αυτό θα
/// έκρυβε εξάρτηση από τον τρέχοντα φάκελο εργασίας — η ίδια σύγκριση θα
/// έδινε άλλο αποτέλεσμα ανάλογα με το πού τρέχει η εφαρμογή. Οι διαδρομές
/// που συγκρίνει η εφαρμογή είναι απόλυτες· μια σχετική δίπλα σε μια απόλυτη
/// είναι ούτως ή άλλως ασαφής και πρέπει να λυθεί από τον καλούντα.
library;

import 'dart:io';

import 'package:path/path.dart' as p;

/// Δείχνουν οι [a] και [b] στο ίδιο αρχείο;
///
/// Η κενή διαδρομή δεν ταιριάζει με τίποτα — ούτε με άλλη κενή. Το κενό δεν
/// είναι αρχείο, και ένα «ναι» εδώ θα έσβηνε εγγραφές που κανείς δεν ζήτησε να
/// αγγιχτούν.
bool pathsReferToSameFile(String a, String b) {
  final ka = filePathKey(a);
  if (ka.isEmpty) return false;
  return ka == filePathKey(b);
}

/// Η κανονική μορφή της [path], για σύγκριση ή για κλειδί σε σύνολα.
///
/// Δύο γραφές του ίδιου αρχείου δίνουν το ίδιο κλειδί. Κενή διαδρομή δίνει
/// κενό κλειδί, ώστε ο καλών να ξεχωρίζει το «άγνωστο» χωρίς δεύτερο έλεγχο.
String filePathKey(String path) {
  final trimmed = path.trim();
  if (trimmed.isEmpty) return '';
  if (!Platform.isWindows) return p.normalize(trimmed);

  // Στα Windows οι δύο κάθετοι είναι ισοδύναμοι διαχωριστές, οπότε η μία
  // μορφή γίνεται η άλλη πριν από οτιδήποτε. Εκτός Windows η ανάποδη κάθετος
  // είναι κανονικός χαρακτήρας ονόματος αρχείου και δεν αγγίζεται ποτέ.
  final unified = trimmed.replaceAll('/', r'\');

  // Η διπλή κάθετος της αρχής είναι ο διακομιστής, όχι διπλοτυπία: το
  // `normalize` θα την ισοπέδωνε σε μία και η «\\POPINIO\Share» θα γινόταν
  // φάκελος του τοπικού δίσκου. Φυλάγεται, κανονικοποιείται το υπόλοιπο, και
  // ξαναμπαίνει.
  final isUnc = unified.startsWith(r'\\');
  final body = isUnc ? unified.substring(2) : unified;
  final normalized = p.windows.normalize(body);
  return (isUnc ? '\\\\$normalized' : normalized).toLowerCase();
}
