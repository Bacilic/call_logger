/// Ο κατάλογος των δικαιωμάτων που μπορεί να ρυθμίσει ο διαχειριστής.
///
/// **Κάθε δικαίωμα δηλώνει εδώ την προεπιλογή του.** Στην καρτέλα του χρήστη
/// αποθηκεύεται μόνο ό,τι ο διαχειριστής άλλαξε ρητά, οπότε η προσθήκη νέου
/// δικαιώματος δεν αγγίζει κανένα υπάρχον προφίλ: όσοι δεν το έχουν ρυθμίσει
/// παίρνουν αυτόματα την προεπιλογή που γράφεται εδώ.
///
/// Σχεδόν όλα επιτρέπονται από προεπιλογή. Η προεπιλογή γράφεται ρητά σε κάθε
/// εγγραφή ώστε η μελλοντική αλλαγή της να φαίνεται.
///
/// **Τι ΔΕΝ είναι εδώ, και γιατί (απόφαση Διευθυντή 21/08/2026).** Ο κατάλογος
/// καλύπτει σκόπιμα μόνο ενέργειες όπου το **λάθος είναι ακριβό ή δύσκολα
/// αναστρέψιμο**. Η καθημερινή δουλειά του Καταλόγου —υπάλληλοι, τμήματα και
/// όροφοι, μαζικές διαγραφές— έμεινε ελεύθερη: τα λάθη της είναι αναστρέψιμα
/// και οι πύλες της πολλές εκ σχεδιασμού. Η «Δημοσίευση έκδοσης» έφυγε επειδή
/// η οθόνη της υπάρχει μόνο σε debug build, οπότε το τικ δεν θα ίσχυε ποτέ.
/// **Δικαίωμα που δεν πρόκειται να επιβληθεί δεν μπαίνει εδώ** — η λίστα με τα
/// τικ είναι υπόσχεση, και μια υπόσχεση που δεν τηρείται είναι χειρότερη από
/// την απουσία της.
///
/// **Η διαχείριση χρηστών ΔΕΝ είναι δικαίωμα αυτού του καταλόγου** — δες
/// `PermissionService.canManageOperators`. Όποιος μπορεί να δίνει δικαιώματα
/// μπορεί να τα δώσει και στον εαυτό του.
///
/// Κλειδιά δικαιωμάτων που αφαιρέθηκαν μπορεί να επιβιώνουν σε παλιά προφίλ.
/// Είναι αδρανή: τίποτα δεν τα ρωτά και η λίστα δείχνει μόνο τον κατάλογο.
///
/// **Πρώτη εξαίρεση (Φάση 2, 20/08/2026): το πλήρες αντίγραφο ασφαλείας.**
/// Κλειδωμένη απόφαση: ένα επίσημο αντίγραφο της βάσης, μόνο ο διαχειριστής —
/// αλλιώς κάθε συνάδελφος θα έβγαζε δικά του αντίγραφα σε δικούς του φακέλους
/// και κανείς δεν θα ήξερε ποιο είναι το αληθινό.
///
/// **Το [enforced] λέει αν το δικαίωμα έχει όντως σημείο ελέγχου σήμερα.**
/// Η λίστα με τα τικ δείχνει όλον τον κατάλογο, αλλά σημαίνει ορατά όσα δεν
/// επιβάλλονται ακόμη — αλλιώς ο διαχειριστής θα έβγαζε τικ νομίζοντας ότι
/// κάτι κλείδωσε. Όποιος προσθέτει σημείο ελέγχου, γυρίζει εδώ τη σημαία·
/// ο έλεγχος `app_permission_enforcement_test.dart` δεν αφήνει τη δήλωση να
/// ξεμείνει από την πραγματικότητα.
enum AppPermission {
  manageEquipmentTypes(
    key: 'manage_equipment_types',
    label: 'Αλλαγή τύπων εξοπλισμού',
    allowedByDefault: true,
    enforced: true,
  ),

  /// Κοινή ρύθμιση: από εκεί παίρνουν όλοι τις εκδόσεις. Λάθος διαδρομή δεν
  /// χαλάει τη δουλειά ενός ανθρώπου — σταματά τις ενημερώσεις όλων.
  manageUpdateFolder(
    key: 'manage_update_folder',
    label: 'Ρύθμιση φακέλου ενημερώσεων',
    allowedByDefault: true,
    enforced: true,
  ),
  manageAuditRetention(
    key: 'manage_audit_retention',
    label: 'Πολιτική εκκαθάρισης Ιστορικού',
    allowedByDefault: true,
    enforced: true,
  ),

  /// Μαζί με την **επαναφορά από αντίγραφο** — η μόνη ενέργεια που αντικαθιστά
  /// ολόκληρη την κοινόχρηστη βάση, για όλους ταυτόχρονα.
  databaseMaintenance(
    key: 'database_maintenance',
    label: 'Συντήρηση και επαναφορά βάσης',
    allowedByDefault: true,
    enforced: true,
  ),

  /// `false` από τη Φάση 2: μόνο ο διαχειριστής (ή όποιος πάρει ρητό τικ στη
  /// Φάση 4). Χωρίς συνδεδεμένο χρήστη η πύλη απαντά «ναι» — ζώνη ασφαλείας
  /// από λάθη, όχι κλειδαριά.
  fullBackup(
    key: 'full_backup',
    label: 'Πλήρες αντίγραφο ασφαλείας',
    allowedByDefault: false,
    enforced: true,
  ),

  /// Χρειάζεται έμφαση: η Περιήγηση Βάσης **παρακάμπτει κάθε άλλο δικαίωμα**,
  /// γιατί δείχνει τους ωμούς πίνακες — άρα και ό,τι έχει κρυφτεί αλλού.
  browseDatabase(
    key: 'browse_database',
    label: 'Περιήγηση Βάσης',
    allowedByDefault: true,
    enforced: true,
  );

  const AppPermission({
    required this.key,
    required this.label,
    required this.allowedByDefault,
    required this.enforced,
  });

  /// Το κλειδί που αποθηκεύεται. **Δεν αλλάζει ποτέ** — αποθηκευμένα προφίλ το
  /// αναφέρουν ονομαστικά, οπότε μια μετονομασία θα έσβηνε σιωπηλά ρυθμίσεις.
  final String key;

  /// Πώς διαβάζεται στην οθόνη διαχείρισης.
  final String label;

  final bool allowedByDefault;

  /// Αν υπάρχει σήμερα σημείο ελέγχου που όντως το επιβάλλει.
  ///
  /// `false` σημαίνει «δηλωμένο αλλά ανενεργό»: το τικ αποθηκεύεται κανονικά
  /// και θα πιάσει μόλις μπει ο έλεγχος, αλλά σήμερα δεν εμποδίζει τίποτα.
  final bool enforced;

  /// Όσα δικαιώματα δεν έχουν ακόμη σημείο ελέγχου — τα σημαίνει η λίστα τικ.
  static List<AppPermission> get notYetEnforced =>
      AppPermission.values.where((p) => !p.enforced).toList();

  static AppPermission? byKey(String key) {
    final normalized = key.trim();
    for (final permission in AppPermission.values) {
      if (permission.key == normalized) return permission;
    }
    return null;
  }
}
