import 'task_save_exception.dart';

/// Η εκκρεμότητα διαγράφηκε από άλλον σταθμό όσο ήταν ανοιχτή για
/// επεξεργασία.
///
/// Πετάγεται **πριν** γραφτεί τίποτα: η αποθήκευση γράφει ολόκληρη την
/// καρτέλα, και χωρίς αυτόν τον φρουρό θα επανέφερε σιωπηλά τη διαγραμμένη
/// εκκρεμότητα (απόφαση Διευθυντή 17/10/2026: δεν αποθηκεύεται, ο χρήστης
/// ενημερώνεται).
///
/// Υποκλάση του [TaskSaveException], ώστε κάθε ροή που δεν τη χειρίζεται ρητά
/// να δείχνει ούτως ή άλλως το αληθινό μήνυμα.
class TaskDeletedElsewhereException extends TaskSaveException {
  TaskDeletedElsewhereException()
    : super(
        'Η εκκρεμότητα διαγράφηκε από άλλον σταθμό. '
        'Οι αλλαγές δεν αποθηκεύτηκαν.',
      );
}
