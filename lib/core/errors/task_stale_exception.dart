import '../../features/tasks/models/task.dart';
import 'task_save_exception.dart';

/// Η εγγραφή άλλαξε από άλλον χρήστη μετά την ανάγνωσή της.
///
/// Πετάγεται **πριν** γραφτεί τίποτα: σε κοινόχρηστη βάση η οθόνη κρατά την
/// εικόνα της στιγμής που φόρτωσε, και μια αποθήκευση πάνω σε αυτή θα έσβηνε
/// σιωπηλά τη δουλειά κάποιου άλλου.
///
/// **Υποκλάση του [TaskSaveException] επίτηδες:** αν κάποια ροή ξεχάσει να τη
/// χειριστεί ρητά, πέφτει στο υπάρχον δίχτυ και ο χρήστης διαβάζει κάτι αληθές
/// («κάποιος άλλος την άλλαξε») αντί για ψευδές («δεν ενημερώθηκε»).
class TaskStaleException extends TaskSaveException {
  TaskStaleException({
    required this.fresh,
    required this.attempted,
    this.changedBy,
    this.changedAt,
  }) : super(
         'Κάποιος άλλος άλλαξε αυτή την εκκρεμότητα στο μεταξύ. '
         'Ανανεώστε τη λίστα και δοκιμάστε ξανά.',
       );

  /// Η εγγραφή όπως είναι **τώρα** στη βάση.
  final Task fresh;

  /// Η εγγραφή που πήγε να γραφτεί — η μπαγιάτικη εικόνα της οθόνης.
  final Task attempted;

  /// Ποιος έκανε την τελευταία αλλαγή, από το Ιστορικό.
  ///
  /// Η γραμμή `tasks` δεν κρατά «ποιος με άλλαξε τελευταίος», οπότε το όνομα
  /// έρχεται από την τελευταία εγγραφή Ιστορικού της εκκρεμότητας. `null` όταν
  /// δεν βρεθεί — η αλλαγή μπορεί να έγινε έξω από την εφαρμογή.
  final String? changedBy;

  /// Πότε έγινε η τελευταία αλλαγή, από το Ιστορικό.
  final DateTime? changedAt;
}
