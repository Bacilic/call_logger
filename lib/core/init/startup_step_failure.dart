import '../services/crash_log_service.dart';

/// Καταγράφει την αποτυχία ενός βήματος **νοικοκυριού** χωρίς να τη διαδώσει.
///
/// Τα βήματα αυτά — μεταπτώσεις παλιών πεδίων, σφράγισμα αποθηκευμένων κλειδιών
/// — τρέχουν μέσα στην αρχικοποίηση της βάσης και **δεν επιτρέπεται να τη
/// ρίξουν**: η βάση άνοιξε σωστά, και μια μετάπτωση που δεν πρόλαβε δεν είναι
/// λόγος να μείνει ο χρήστης έξω από τη δουλειά του.
///
/// **Σιωπή όμως δεν σημαίνει αδιαφορία.** Ένα `catch (_) {}` κρύβει τη ρίζα για
/// πάντα: η αστοχία εμφανίζεται εβδομάδες αργότερα ως ανεξήγητη συμπεριφορά —
/// «δεν δουλεύει το AnyDesk» — και κανείς δεν έχει τρόπο να τη συνδέσει με την
/// αιτία της, γιατί δεν έμεινε κανένα ίχνος.
///
/// **Το ημερολόγιο ρωτιέται ανεκτικά, και αυτό είναι ο πυρήνας του κανόνα.**
/// Ένα `CrashLogService.instance` εδώ πετά όταν το ημερολόγιο δεν στήθηκε ποτέ.
/// Το σφάλμα τότε ανεβαίνει στον φρουρό της αρχικοποίησης και η αποτυχία ενός
/// βήματος νοικοκυριού μεταμφιέζεται σε **σφάλμα βάσης** — οθόνη που στέλνει
/// τον χρήστη να ψάξει βλάβη που δεν υπάρχει. Και η στιγμή που λείπει το
/// ημερολόγιο είναι ακριβώς η στιγμή που αυτά τα βήματα αποτυγχάνουν: όταν ο
/// δικτυακός φάκελος δεν απαντά.
///
/// Γι' αυτό η καταγραφή εδώ **δεν πετάει ποτέ**, ό,τι κι αν λείπει.
void reportStartupStepFailure(String label, Object error, StackTrace stack) {
  CrashLogService.instanceOrNull?.logError(
    StateError('$label: $error'),
    stack,
    fatal: false,
  );
}
