/// Ειδοποιήσεις που περιμένουν να φτάσει ο χειριστής στην κύρια οθόνη.
///
/// **Το περιστατικό (28/10/2026):** ο έλεγχος του φακέλου αντιγράφων τρέχει
/// στο παρασκήνιο από την πρώτη στιγμή της εκκίνησης, και ο διάλογός του
/// άνοιγε πάνω από ό,τι βρισκόταν μπροστά — και πάνω από το «Ποιος
/// χρησιμοποιεί την εφαρμογή;». Μια ερώτηση που δεν είναι επείγουσα έκλεβε
/// τη σειρά από μια που πρέπει να απαντηθεί πριν από οτιδήποτε άλλο.
///
/// **Ο κανόνας:** η πύλη ανοίγει μόνο όσο υπάρχει η κύρια οθόνη. Ό,τι ζητηθεί
/// νωρίτερα κρατιέται και εμφανίζεται μόλις ανοίξει — καμία ειδοποίηση δεν
/// χάνεται, απλώς περιμένει. Κάθε οθόνη πριν από την κύρια (κάρτα εκκίνησης,
/// επιλογή χρήστη, ορισμός διαχειριστή, οθόνη σφάλματος) καλύπτεται χωρίς να
/// χρειάζεται να το ξέρει.
class MainScreenAnnouncements {
  MainScreenAnnouncements._();

  static bool _open = false;
  static final List<void Function()> _pending = [];

  /// Είναι η κύρια οθόνη μπροστά στον χειριστή;
  static bool get isOpen => _open;

  /// Εμφανίζει τώρα, αν η κύρια οθόνη υπάρχει· αλλιώς μόλις εμφανιστεί.
  static void announce(void Function() show) {
    if (_open) {
      show();
      return;
    }
    _pending.add(show);
  }

  /// Η κύρια οθόνη εμφανίστηκε: ό,τι περίμενε, βγαίνει με τη σειρά του.
  static void open() {
    _open = true;
    final waiting = List.of(_pending);
    _pending.clear();
    for (final show in waiting) {
      show();
    }
  }

  /// Η κύρια οθόνη έφυγε (π.χ. αλλαγή βάσης): ό,τι ζητηθεί ως την επόμενη
  /// εμφάνισή της περιμένει ξανά.
  static void close() => _open = false;

  /// Μηδενισμός για τα τεστ — η κατάσταση είναι καθολική.
  static void resetForTest() {
    _open = false;
    _pending.clear();
  }
}
