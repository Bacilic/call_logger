/// Πώς διαβάζεται μια λογική ρύθμιση αποθηκευμένη ως κείμενο.
///
/// Μία συνάρτηση για όλους: οι τιμές γράφτηκαν από διαφορετικές εκδόσεις της
/// εφαρμογής («1», «true»), και μια δεύτερη ανάγνωση με δικούς της κανόνες θα
/// απέκλινε σιωπηλά από την πρώτη.
bool parseBoolAppSetting(String? raw) {
  final t = (raw ?? '').trim().toLowerCase();
  return t == '1' || t == 'true' || t == 'yes';
}
