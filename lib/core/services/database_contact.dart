/// Πότε αυτή η εκτέλεση μίλησε τελευταία φορά **με επιτυχία** με τη βάση.
///
/// Το γράφει ο παλμός παρουσίας σε κάθε επιτυχημένη εγγραφή του — τη μόνη
/// τακτική επαφή με τη βάση που γίνεται όσο ζει η εφαρμογή, ακόμη κι όταν
/// κανείς δεν κάθεται μπροστά της. Το διαβάζει το σημάδι ζωής στον κοινό
/// φάκελο, ώστε οι άλλοι σταθμοί να ξεχωρίζουν την εφαρμογή που δουλεύει από
/// εκείνη που τρέχει με νεκρή σύνδεση.
class DatabaseContact {
  DatabaseContact._();

  static DateTime? _last;

  static DateTime? get last => _last;

  static void note(DateTime at) => _last = at;

  /// Μηδενισμός για τα τεστ — και για την αλλαγή βάσης, όπου η επαφή με την
  /// προηγούμενη δεν λέει τίποτα για τη νέα.
  static void reset() => _last = null;
}
