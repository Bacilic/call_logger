import 'package:flutter/foundation.dart';

import '../models/operator.dart';

/// Ποιος χρησιμοποιεί την εφαρμογή αυτή τη στιγμή — **η μοναδική πηγή**.
///
/// Η ταυτότητα ορίζεται στην εκκίνηση από τον αναγνωριστή προφίλ, και εν
/// λειτουργία μόνο από την «Αλλαγή χρήστη». Όλα τα υπόλοιπα (πρώτα απ' όλα το
/// Ιστορικό) τη ρωτούν από εδώ. Δύο σημεία που απαντούν στο ίδιο ερώτημα
/// κάποια μέρα θα διαφωνήσουν σιωπηλά.
///
/// Είναι σκόπιμα καθολική: το Ιστορικό γράφεται βαθιά μέσα στα repositories,
/// σε δεκάδες σημεία που δεν έχουν —και δεν πρέπει να αποκτήσουν— γνώση της
/// διεπαφής. Ο **μοναδικός** που την ορίζει είναι ο αναγνωριστής.
/// Γιατί άλλαξε η ταυτότητα — δύο πολύ διαφορετικά γεγονότα.
///
/// Η διάκριση δεν είναι λεπτομέρεια: κρίνει **αν κάποιος χάνει τη δουλειά που
/// έχει ανοιχτή**. Ένα `bool` δεν θα το έλεγε — θα έλεγε τι να κάνει ο
/// παραλήπτης, όχι τι συνέβη.
enum OperatorChangeCause {
  /// **Άλλος άνθρωπος** κάθεται τώρα: εκκίνηση, «Αλλαγή χρήστη», αλλαγή βάσης.
  ///
  /// Ό,τι άφησε ανοιχτό ο προηγούμενος δεν ανήκει στον επόμενο — οι οθόνες που
  /// κρίνονται από δικαίωμα κλείνουν, και οι προσωπικές ρυθμίσεις όλες
  /// ξαναδιαβάζονται.
  identitySwitched,

  /// **Ο ίδιος άνθρωπος**, με φρέσκα στοιχεία από την κοινόχρηστη βάση.
  ///
  /// Ο διαχειριστής άλλαξε κάτι από άλλον σταθμό. Κανείς δεν σηκώθηκε από την
  /// καρέκλα, άρα κανείς δεν πετάγεται έξω από τη δουλειά του: τα δικαιώματα
  /// ισχύουν από την **επόμενη** φορά που θα ζητηθεί η πόρτα.
  profileRefreshed,
}

class CurrentOperator {
  const CurrentOperator._();

  /// Παρατηρήσιμη εσωτερικά, ώστε ό,τι δείχνει το όνομα στην οθόνη (π.χ. η
  /// ένδειξη στη μπάρα πλοήγησης) να ενημερώνεται μόνο του όταν αλλάζει ο
  /// χρήστης — χωρίς δεύτερη πηγή αλήθειας.
  static final ValueNotifier<Operator?> _active = ValueNotifier<Operator?>(
    null,
  );

  /// Ο ενεργός χρήστης· `null` όσο δεν έχει αναγνωριστεί κανείς (π.χ. πριν
  /// ανοίξει η βάση, ή μέσα σε ελέγχους).
  static Operator? get active => _active.value;

  /// Για widgets που δείχνουν την ταυτότητα και πρέπει να την παρακολουθούν
  /// ζωντανά. Μόνο ανάγνωση — η εγγραφή γίνεται πάντα μέσω [activate]/[reset].
  static ValueListenable<Operator?> get listenable => _active;

  /// Γιατί άλλαξε τελευταία φορά η ταυτότητα.
  ///
  /// Διαβάζεται από όποιον ακούει το [listenable] και πρέπει να ξεχωρίσει το
  /// «κάθισε άλλος» από το «άλλαξαν τα στοιχεία του ίδιου».
  static OperatorChangeCause get lastChangeCause => _lastChangeCause;
  static OperatorChangeCause _lastChangeCause =
      OperatorChangeCause.identitySwitched;

  /// Ορίζεται **μόνο** από τον αναγνωριστή προφίλ — στην εκκίνηση και στην
  /// «Αλλαγή χρήστη».
  static void activate(Operator? operator) {
    _lastChangeCause = OperatorChangeCause.identitySwitched;
    _active.value = operator;
  }

  /// Φρέσκα στοιχεία για τον **ίδιο** άνθρωπο, από την κοινόχρηστη βάση.
  ///
  /// Χωριστή πόρτα από το [activate] επίτηδες: εκείνη λέει «άλλαξε ο χρήστης»,
  /// αυτή λέει «άλλαξαν τα στοιχεία του». Ο παραλήπτης χρειάζεται τη διαφορά —
  /// στη δεύτερη περίπτωση κανείς δεν σηκώθηκε από την καρέκλα, οπότε καμία
  /// ανοιχτή οθόνη δεν κλείνει και καμία προσωπική ρύθμιση δεν ξαναδιαβάζεται.
  ///
  /// Καλείται μόνο όταν η σύγκριση έδειξε πραγματική αλλαγή — δες
  /// `refreshCurrentOperatorProfile`.
  static void refreshActive(Operator operator) {
    _lastChangeCause = OperatorChangeCause.profileRefreshed;
    _active.value = operator;
  }

  /// Το όνομα που σφραγίζει το Ιστορικό.
  ///
  /// Όταν δεν έχει αναγνωριστεί κανείς επιστρέφει την παύλα — την ίδια ένδειξη
  /// «άγνωστος» που έγραφε η εφαρμογή πριν αποκτήσει προφίλ, ώστε οι παλιές
  /// εγγραφές και οι νέες να μιλούν την ίδια γλώσσα.
  static String get auditName {
    final name = _active.value?.displayName.trim() ?? '';
    return name.isEmpty ? unknownAuditName : name;
  }

  /// Η ένδειξη «δεν ξέρουμε ποιος» στο Ιστορικό.
  static const String unknownAuditName = '—';

  /// Μηδενίζει την ταυτότητα — για ελέγχους και για την αλλαγή βάσης.
  static void reset() {
    _lastChangeCause = OperatorChangeCause.identitySwitched;
    _active.value = null;
  }
}
