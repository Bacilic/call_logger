import 'app_instance_registry.dart';

/// Έως ποιο σχήμα βάσης διαβάζει η κάθε **έκδοση** της εφαρμογής.
///
/// **Γιατί ζει σε μνήμη και όχι πίσω από ανάγνωση ρυθμίσεων.** Η απάντηση
/// χρειάζεται μέσα στη φόρτωση των ανοιχτών συνεδριών — μια διαδρομή που τρέχει
/// και σε οθόνες όπου η βάση **απέτυχε** να ανοίξει, και που έχει ρητό
/// συμβόλαιο: καμία κλήση που μπορεί να μην ολοκληρωθεί. Η ανάγνωση των
/// τοπικών ρυθμίσεων περνά από κανάλι του συστήματος και μέσα σε `testWidgets`
/// δεν απαντά ποτέ — κρεμάει τον έλεγχο αντί να τον κοκκινίσει, που είναι
/// χειρότερο γιατί η εκτέλεση κλείνει σαν να πέρασε.
///
/// **Το μητρώο διαβάζεται ήδη αλλού**, όταν καταγράφεται το τρέχον αντίγραφο
/// στην οθόνη της βάσης. Εκείνη η διαδρομή απλώς αφήνει εδώ ό,τι βρήκε, και η
/// φόρτωση συνεδριών το διαβάζει **σύγχρονα** χωρίς να πληρώσει τίποτα.
///
/// **Η άγνοια είναι έγκυρη απάντηση.** Όσο κανείς δεν έχει αφήσει μητρώο —
/// στην εκκίνηση, στα τεστ, σε οθόνη που δεν το χρειάστηκε ποτέ — η απάντηση
/// είναι «δεν ξέρω», και όποιος ρωτά οφείλει να σωπάσει αντί να μαντέψει.
class KnownSchemaCeilings {
  const KnownSchemaCeilings._();

  static List<AppInstanceRecord> _known = const [];

  /// Κρατά το μητρώο που μόλις διαβάστηκε.
  static void remember(List<AppInstanceRecord> records) {
    _known = List.unmodifiable(records);
  }

  /// Έως ποιο σχήμα διαβάζει η έκδοση [version]; `null` όταν δεν το ξέρουμε.
  ///
  /// Το ταβάνι είναι ιδιότητα του build: αν η 0.57.1 φτάνει ως το 66 εδώ,
  /// φτάνει ως το 66 και στον σταθμό του συναδέλφου. Γι' αυτό το τοπικό μητρώο
  /// απαντά και για **ξένους** σταθμούς, από τους οποίους ξέρουμε μόνο τον
  /// αριθμό έκδοσης.
  static int? forVersion(String? version) =>
      AppInstanceRegistry.schemaCeilingForVersion(_known, version);

  /// Ξεχνά ό,τι κρατήθηκε. Υπάρχει για τα τεστ.
  static void resetForTest() => _known = const [];
}
