import 'package:flutter/material.dart';

import 'settings_service.dart';

/// Το πορτοκαλί της προειδοποίησης «λείπει λεξικό-πυρήνας».
///
/// Ένα σημείο για εικονίδιο και κείμενο: δύο αποχρώσεις που θέλουν να πουν το
/// ίδιο πράγμα αποκλίνουν στην πρώτη αλλαγή.
const Color kMissingCoreLexiconColor = Color(0xFFB25E00);

/// Ο ορθογραφικός έλεγχος και ό,τι κρέμεται από αυτόν, σε ένα σημείο.
///
/// Δύο ροές τον σβήνουν —ο διακόπτης των Ρυθμίσεων και η αφαίρεση του
/// λεξικού-πυρήνα— και οφείλουν να αφήνουν την εφαρμογή στην ίδια κατάσταση.
/// Γραμμένο μία φορά, ώστε ο δεύτερος καλών να μην μπορεί να ξεχάσει το μισό.
abstract final class SpellCheckActivation {
  SpellCheckActivation._();

  /// Σβήνει τον ορθογραφικό έλεγχο μαζί με την προβολή του Λεξικού.
  ///
  /// Το «Λεξικό» κρύβεται ούτως ή άλλως όσο ο έλεγχος είναι κλειστός· η
  /// αποθηκευμένη ρύθμιση ακολουθεί, ώστε να μη λέει άλλα από αυτά που δείχνει
  /// η οθόνη.
  static Future<void> disable(SettingsService settings) async {
    await settings.windowUi.setEnableSpellCheck(false);
    await settings.windowUi.setShowDictionaryNav(false);
  }
}

/// Το κείμενο κάτω από τον διακόπτη «Ορθογραφικός έλεγχος».
///
/// Χωρίς πυρήνα ο διακόπτης δεν είναι άχρηστος — απλώς κάνει κάτι άλλο από
/// αυτό που περιμένει ο χρήστης, και του το λέμε πριν το ανακαλύψει μόνος του.
String spellCheckSubtitle({required bool coreLexiconLoaded}) {
  if (coreLexiconLoaded) {
    return 'Ενσωματωμένο λεξικό (ελληνικά + IT)· σημαντικό σε Windows όπου '
        'δεν υπάρχει εγγενής έλεγχος.';
  }
  return 'Δεν έχει φορτωθεί λεξικό-πυρήνας. Ο έλεγχος λειτουργεί μόνο με τις '
      'λέξεις του προσωπικού σας λεξικού, οπότε σχεδόν όλες οι υπόλοιπες θα '
      'εμφανίζονται ως λάθος.';
}

/// Η προειδοποίηση όταν ο έλεγχος ανάβει χωρίς λεξικό-πυρήνα.
const String kSpellCheckWithoutCoreWarning =
    'Ο ορθογραφικός έλεγχος άναψε χωρίς λεξικό-πυρήνα: μέχρι να φορτώσετε ένα, '
    'σχεδόν κάθε λέξη θα υπογραμμίζεται ως άγνωστη.';

/// Πρέπει να ειδοποιηθεί ο χρήστης γι' αυτή την αλλαγή του διακόπτη;
///
/// Μόνο στο άναμμα και μόνο χωρίς πυρήνα. Το σβήσιμο δεν έχει τίποτα να πει,
/// και με φορτωμένο λεξικό η ρύθμιση κάνει ακριβώς ό,τι υπόσχεται.
bool shouldWarnEnablingSpellCheck({
  required bool turningOn,
  required bool coreLexiconLoaded,
}) {
  return turningOn && !coreLexiconLoaded;
}
