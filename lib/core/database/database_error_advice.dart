// Τι συμβουλεύουμε τον χειριστή όταν η βάση δεν απαντά.
//
// Η **διάγνωση** («το αρχείο φαίνεται κατεστραμμένο») είναι ίδια όπου κι αν
// συμβεί το σφάλμα. Η **συμβουλή** όμως όχι: εξαρτάται από το τι έκανε ο
// χειριστής τη στιγμή που το είδε. Όσο οι δύο ήταν μαζί στο ίδιο πεδίο, το
// κείμενο της εκκίνησης —«επαληθεύστε ότι επιλέξατε σωστό αρχείο .db»—
// εμφανιζόταν και σε κάποιον που απλώς πήγαινε να καταγράψει μια κλήση, και
// τον έστελνε να ψάξει επιλογή που δεν είχε κάνει ποτέ.

import 'database_init_result.dart';

/// Τι έκανε ο χειριστής όταν χτύπησε το σφάλμα.
enum DatabaseErrorMoment {
  /// Διαχειρίζεται αρχείο βάσης: επιλογή, αλλαγή διαδρομής, εκκίνηση.
  /// Εδώ η συμβουλή «ελέγξτε το αρχείο που διαλέξατε» είναι ακριβώς σωστή.
  choosingDatabaseFile,

  /// Δούλευε κανονικά και κάτι δεν διαβάστηκε — ο κατάλογος, μια λίστα.
  usingTheApp,

  /// Μόλις πάτησε αποθήκευση. Το πρώτο που πρέπει να μάθει δεν είναι η αιτία·
  /// είναι ότι η δουλειά του **δεν** καταχωρήθηκε.
  saving,
}

/// Η συμβουλή που ταιριάζει στη [moment], ή `null` όταν δεν έχουμε κάτι
/// χρήσιμο να πούμε.
///
/// Στις στιγμές που ο χειριστής **δεν** διαχειρίζεται αρχείο, η συμβουλή είναι
/// δική μας και σταθερή: μία πρόταση που λέει τι σημαίνει και πού να πάει.
/// Το ωμό κείμενο του SQLite δεν περνά από εδώ — δεν το διαβάζει άνθρωπος, και
/// ζει ήδη στο αρχείο καταγραφής.
String? databaseErrorAdvice({
  required DatabaseInitResult result,
  required DatabaseErrorMoment moment,
}) {
  switch (moment) {
    case DatabaseErrorMoment.choosingDatabaseFile:
      final existing = result.details?.trim();
      return (existing == null || existing.isEmpty) ? null : existing;

    case DatabaseErrorMoment.usingTheApp:
      return 'Τα δεδομένα δεν διαβάστηκαν από τη βάση. Δοκιμάστε ξανά — αν το '
          'πρόβλημα επιμένει, ανοίξτε τις Ρυθμίσεις βάσης για να αλλάξετε '
          'αρχείο ή να επαναφέρετε από αντίγραφο ασφαλείας.';

    case DatabaseErrorMoment.saving:
      return 'Η αλλαγή σας ΔΕΝ αποθηκεύτηκε. Σημειώστε την και δοκιμάστε ξανά '
          '— αν το πρόβλημα επιμένει, ανοίξτε τις Ρυθμίσεις βάσης για να '
          'αλλάξετε αρχείο ή να επαναφέρετε από αντίγραφο ασφαλείας.';
  }
}
