/// Η **μία** ερώτηση «αποκρίνεται η βάση;», και το σπίτι της.
///
/// Όλες οι πόρτες που κρίνουν αν η βάση απαντά —η επίλυση διαδρομής στην
/// εκκίνηση, ο φύλακας προσβασιμότητας, ο φρουρός επιστροφής στη δικτυακή—
/// ρωτούν από εδώ. Ζει σε δικό του αρχείο χωρίς εξαρτήσεις πέρα από το
/// `dart:io` ακριβώς γι' αυτό: έτσι μπορεί να τη ρωτήσει και η επίλυση
/// διαδρομής, που βρίσκεται **κάτω** από τον φύλακα στη σειρά των εξαρτήσεων.
library;

import 'dart:async';
import 'dart:io';

/// Ρωτά το αρχείο της βάσης αν είναι ακόμη εκεί — **χωρίς να κρεμάσει**.
///
/// Δύο προφυλάξεις, και οι δύο απαραίτητες:
///  * **Όριο χρόνου:** μια δικτυακή διαδρομή που δεν αποκρίνεται μπορεί να
///    αργήσει δεκάδες δευτερόλεπτα λόγω SMB. Ο φύλακας δεν επιτρέπεται να
///    κολλήσει εκεί που κόλλησε η εφαρμογή.
///  * **try/catch:** σε άφταστη διαδρομή δικτύου τα Windows **πετούν**
///    εξαίρεση αντί να απαντήσουν «δεν υπάρχει».
///
/// Ρωτά για το **μέγεθος** και όχι για την ύπαρξη: το μέγεθος απαιτεί
/// πραγματικό άνοιγμα, ενώ η ύπαρξη μπορεί να απαντηθεί από μνήμη του
/// συστήματος και να πει «όλα καλά» για αρχείο που δεν διαβάζεται πια.
///
/// **Κενή διαδρομή σημαίνει «δεν υπάρχει τίποτα να ρωτηθεί»** και απαντιέται
/// καταφατικά: όποιος ρωτά οφείλει να έχει κρίνει πρωτύτερα την περίπτωση
/// «η βάση δεν έχει ρυθμιστεί ακόμη», που δεν είναι αστοχία του δικτύου.
Future<bool> probeDatabaseFile(
  String path, {
  Duration timeout = const Duration(seconds: 5),
}) async {
  if (path.trim().isEmpty) return true;
  try {
    await File(path).length().timeout(timeout);
    return true;
  } catch (_) {
    return false;
  }
}
