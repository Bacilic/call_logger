/// Αφήνει μια ακριβή ανανέωση να τρέξει το πολύ μία φορά ανά [minimumGap].
///
/// **Γιατί υπάρχει.** Ο κύκλος που μαθαίνει «κάποιος άλλος έγραψε στη βάση»
/// χτυπά κάθε 12 δευτερόλεπτα, γιατί οι λίστες που ανανεώνει είναι φθηνές. Δεν
/// είναι όμως όλες: τα στατιστικά της βάσης μετρούν τις γραμμές **κάθε** πίνακα
/// με χωριστό ερώτημα και σαρώνουν τον φάκελο των αντιγράφων. Σε γραφείο όπου
/// τέσσερις σταθμοί καταγράφουν κλήσεις, ο μετρητής αλλάζει διαρκώς και η ίδια
/// ακριβή δουλειά θα έτρεχε τριακόσιες φορές την ώρα, σε κάθε μηχάνημα με την
/// οθόνη ανοιχτή, πάνω από το δίκτυο.
///
/// **Ένας ρυθμός ανά κόστος, όχι ένας για όλα.** Ο ρυθμιστής δεν αναβάλλει και
/// δεν κρατά τίποτα σε ουρά: απαντά «τώρα ναι» ή «τώρα όχι», και η επόμενη
/// ξένη εγγραφή θα ξαναρωτήσει ούτως ή άλλως μέσα σε δευτερόλεπτα. Μια
/// ανανέωση που χάνεται εδώ δεν χάνεται στην πράξη — απλώς γίνεται λίγο
/// αργότερα, όταν επιτρέπεται.
///
/// Το ρολόι δίνεται απ' έξω ώστε ο κανόνας να ελέγχεται χωρίς αναμονή.
class RefreshThrottle {
  RefreshThrottle({required this.minimumGap, DateTime Function()? now})
    : _now = now ?? DateTime.now;

  /// Το ελάχιστο διάστημα ανάμεσα σε δύο εγκρίσεις.
  final Duration minimumGap;

  final DateTime Function() _now;

  DateTime? _lastAllowed;

  /// Πότε εγκρίθηκε τελευταία φορά· `null` όσο δεν έχει εγκριθεί ποτέ.
  DateTime? get lastAllowedAt => _lastAllowed;

  /// Επιτρέπεται η ανανέωση τώρα;
  ///
  /// **Η πρώτη φορά περνά πάντα.** Μόλις ανοίξει η οθόνη, η πρώτη ξένη εγγραφή
  /// οφείλει να φανεί αμέσως: ένα αρχικό μπλοκάρισμα θα σήμαινε ότι ο χρήστης
  /// κοιτά μπαγιάτικη εικόνα ακριβώς τη στιγμή που άνοιξε την οθόνη για να δει
  /// τι συμβαίνει.
  ///
  /// Η κλήση έχει **παρενέργεια**: ένα «ναι» ξεκινά το νέο διάστημα. Γι' αυτό
  /// ρωτιέται μόνο όταν η ανανέωση πρόκειται όντως να γίνει.
  bool allow() {
    final at = _now();
    final last = _lastAllowed;
    if (last != null && at.difference(last) < minimumGap) return false;
    _lastAllowed = at;
    return true;
  }

  /// Ξεχνά την τελευταία έγκριση — η επόμενη [allow] περνά.
  ///
  /// Χρειάζεται όταν αλλάζει η ίδια η βάση: η προηγούμενη εικόνα δεν αφορά πια
  /// το αρχείο που κοιτάμε, και μια αναμονή γι' αυτήν θα κρατούσε στην οθόνη
  /// νούμερα άλλης βάσης.
  void reset() => _lastAllowed = null;
}
