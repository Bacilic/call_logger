/// Πότε το τμήμα μιας κλήσης λογίζεται **διαγραμμένο**.
///
/// **Το τμήμα δεν έχει σύνδεση, μόνο όνομα.** Ο πίνακας των κλήσεων κρατά
/// `department_text` και κανένα `department_id` — άρα η μόνη γέφυρα προς τον
/// Κατάλογο είναι το ίδιο το όνομα. Αυτό γεννά ένα ερώτημα που ο καλών και ο
/// εξοπλισμός δεν έχουν: ένα όνομα που δεν ταιριάζει πουθενά μπορεί να είναι
/// **διαγραμμένο τμήμα** ή απλώς **ορθογραφικό λάθος**.
///
/// **Ο όρος που κάνει τη δουλειά:** υπάρχει τμήμα με αυτό το όνομα
/// **σημειωμένο ως διαγραμμένο** — άρα υπήρξε πράγματι και χάθηκε. Χωρίς
/// αυτόν, στη βάση του νοσοκομείου θα σημαδεύονταν ως «διαγραμμένα» 16 κλήσεις
/// με ορθογραφικά («Περιπατιτικό», «Προτόκωλο») απέναντι σε **μία** πραγματική
/// διαγραφή — δεκαεπτά φορές περισσότερος θόρυβος από σήμα.
///
/// **Ο δεύτερος όρος** («κανένα ζωντανό με το ίδιο όνομα») είναι αμυντικός, όχι
/// καθημερινός: ο μοναδικός δείκτης του Καταλόγου δεν επιτρέπει σήμερα να
/// συνυπάρχουν διαγραμμένο και ζωντανό τμήμα με το ίδιο όνομα. Μένει γιατί
/// κοστίζει τίποτα και γιατί το κριτήριο δεν πρέπει να εξαρτά την ορθότητά του
/// από περιορισμό που ζει αλλού.
const String kCallDepartmentIsDeletedSql = '''
      CASE
        WHEN TRIM(COALESCE(calls.department_text, '')) <> ''
         AND EXISTS (
               SELECT 1 FROM departments dept_del
               WHERE dept_del.is_deleted = 1
                 AND dept_del.name = calls.department_text
             )
         AND NOT EXISTS (
               SELECT 1 FROM departments dept_live
               WHERE dept_live.is_deleted = 0
                 AND dept_live.name = calls.department_text
             )
        THEN 1 ELSE 0
      END AS department_is_deleted''';
