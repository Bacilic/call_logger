/// Πότε μια **πραγματική** πράξη της εφαρμογής μπλοκάρεται — και ποιος το
/// μαθαίνει.
///
/// **Το κενό που κλείνει (δοκιμή πεδίου 24/09/2026):** ο φύλακας της βάσης
/// ρωτά με μια **ανάγνωση** (`PRAGMA data_version`). Ένα αποκλειστικό κλείδωμα
/// αφήνει τις αναγνώσεις να περνούν και μπλοκάρει μόνο τις **εγγραφές** — έτσι
/// ο φύλακας απαντούσε «όλα καλά» τη στιγμή που μια αποθήκευση πέθαινε.
/// Μετρημένο: ενώ κρατούσε κλείδωμα 45 δευτερολέπτων, ο διπλανός σταθμός
/// έχασε τον παλμό παρουσίας του στα 18 δευτερόλεπτα και καμία λωρίδα δεν
/// άναψε.
///
/// **Η λύση είναι να ακούει αντί να ρωτά.** Όποια πράξη κολλήσει το ξέρει ήδη
/// — και το ξέρει με τη μόνη πράξη που μετράει, τη δική της. Αφήνει το μήνυμα
/// εδώ· ο φύλακας το μαζεύει.
library;

/// Η θυρίδα όπου μια πράξη αφήνει το «κάτι με μπλόκαρε τώρα».
///
/// **Σκέτο γεγονός, χωρίς αιτία.** Η πράξη ξέρει ότι μπλοκαρίστηκε, δεν ξέρει
/// γιατί: το ίδιο όριο χρόνου χτυπά και σε κλείδωμα συναδέλφου και σε νεκρή
/// σύνδεση. Η διάκριση ανήκει στον φύλακα, που έχει την ιστορία· μια εικασία
/// από εδώ θα έδειχνε πορτοκαλί λωρίδα σε κάθε αργό αντίγραφο ασφαλείας.
class DatabaseStallReports {
  DatabaseStallReports._();

  static void Function()? _listener;

  /// Εγγράφεται **μόνο ο φύλακας**, και ξεγράφεται όταν σταματά.
  static void listen(void Function()? listener) => _listener = listener;

  /// Το καλεί όποια πράξη δεν πρόλαβε να τελειώσει.
  static void report() => _listener?.call();

  /// Ο ακροατής είναι καθολικός και δεν επιτρέπεται να ταξιδεύει από τον έναν
  /// έλεγχο στον επόμενο.
  static void resetForTest() => _listener = null;
}

/// Λέει αυτό το σφάλμα ότι η βάση ήταν **πιασμένη**;
///
/// Η ίδια κρίση χρειαζόταν σε τρία σημεία (ο έλεγχος κλειδώματος, η κρίση της
/// ζωντανής σύνδεσης, και τώρα η αναφορά της πραγματικής πράξης). Ζει σε ένα,
/// ώστε να μην αποκλίνουν σιωπηλά.
bool isDatabaseLockedError(Object error) {
  final lower = error.toString().toLowerCase();
  return lower.contains('database is locked') || lower.contains('sqlite_busy');
}
