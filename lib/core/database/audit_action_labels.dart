/// Οι ενέργειες που ξέρει ο κατάλογος — για τον έλεγχο ότι καμία ενέργεια
/// του κώδικα δεν φτάνει στην οθόνη ωμή.
Iterable<String> get knownAuditActions => _kAuditActionVerbsEl.keys;

/// Το ρήμα της ενέργειας, χωρίς την οντότητα: «Διαγραφή», «Τροποποίηση».
///
/// Άγνωστη ενέργεια επιστρέφεται όπως γράφτηκε — προτιμότερο από το να
/// εξαφανιστεί ή να βγει με λάθος τόνους από μηχανική μετατροπή.
String auditActionVerbEl(String? action) {
  final raw = action?.trim() ?? '';
  if (raw.isEmpty) return '';
  return _kAuditActionVerbsEl[raw] ?? raw;
}

/// «Υπάλληλος - Διαγραφή»: η ετικέτα που δείχνει η γραμμή, το φίλτρο
/// «Ενέργεια» και το πάνελ λεπτομερειών, και που βρίσκει η αναζήτηση.
///
/// Η ίδια λέξη «ΔΙΑΓΡΑΦΗ» γράφεται για υπάλληλο, τμήμα και κλήση· μόνο ο τύπος
/// οντότητας τις ξεχωρίζει, γι' αυτό η ετικέτα βγαίνει πάντα από το ζεύγος.
String auditActionLabelEl({String? entityType, String? action}) {
  final verb = auditActionVerbEl(action);
  final type = entityType?.trim() ?? '';
  final entity = type.isEmpty ? '' : databaseEntityTypeLabelEl(type);
  if (entity.isEmpty) return verb;
  if (verb.isEmpty) return entity;
  return '$entity - $verb';
}

/// Οι τιμές `entity_type` που καλύπτει το φίλτρο «Τύπος οντότητας».
///
/// Οι μαζικές ενημερώσεις γράφονται με δικό τους τύπο, αλλά δεν είναι
/// οντότητα: αφορούν υπαλλήλους, τμήματα ή εξοπλισμό, και το φίλτρο της
/// οντότητας οφείλει να τις πιάνει μαζί με τις μεμονωμένες αλλαγές.
List<String> auditEntityTypeFamily(String entityType) {
  final type = entityType.trim();
  return switch (type) {
    AuditEntityTypes.user => const [
      AuditEntityTypes.user,
      AuditEntityTypes.bulkUsers,
    ],
    AuditEntityTypes.department => const [
      AuditEntityTypes.department,
      AuditEntityTypes.bulkDepartments,
    ],
    AuditEntityTypes.equipment => const [
      AuditEntityTypes.equipment,
      AuditEntityTypes.bulkEquipment,
    ],
    _ => [type],
  };
}
