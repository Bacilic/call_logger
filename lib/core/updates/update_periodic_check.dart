import 'dart:async';

import 'package:flutter_riverpod/flutter_riverpod.dart';

import 'update_providers.dart';

/// Κάθε πότε ξανατρέχει μόνος του ο έλεγχος νέας έκδοσης.
///
/// Μία ώρα: ο έλεγχος είναι μια φθηνή ανάγνωση του `version.json` από τον
/// κοινόχρηστο φάκελο του τοπικού δικτύου, και με ρυθμό ~μίας δημοσίευσης την
/// ημέρα η καθυστέρηση ανακάλυψης έως μία ώρα δεν παίζει κανένα ρόλο.
/// Σταθερά — όχι ρύθμιση: μια επιλογή «διάστημα ελέγχου» θα ήταν θόρυβος
/// για τους χρήστες.
const Duration kUpdatePeriodicCheckInterval = Duration(hours: 1);

/// Περιοδικός παλμός ελέγχου νέας έκδοσης — για εφαρμογή που μένει ανοιχτή
/// μέρες: χωρίς αυτόν, μηχάνημα που δεν επανεκκινεί δεν μαθαίνει ποτέ ότι
/// βγήκε νέα έκδοση.
///
/// Μόνο ακυρώνει την προσωρινή αποθήκευση του [updateCheckProvider]· ό,τι
/// ακολουθεί (κόκκινη κουκίδα έκδοσης, μήνυμα «νέα έκδοση» μία φορά ανά
/// συνεδρία, ακύρωση παλιότερης εκκρεμούς ενημέρωσης) γίνεται από τους
/// υπάρχοντες μηχανισμούς που ήδη ακούν τον έλεγχο.
///
/// Ενεργοποιείται με ένα `ref.watch` από το κέλυφος της εφαρμογής.
final updatePeriodicCheckProvider = Provider<void>((ref) {
  final timer = Timer.periodic(kUpdatePeriodicCheckInterval, (_) {
    ref.invalidate(updateCheckProvider);
  });
  ref.onDispose(timer.cancel);
});
