// Τι ΔΕΝ επιτρέπεται να ταξιδέψει μέσα σε ένα πακέτο ενημέρωσης.
//
// Ένα πακέτο κουβαλά την **εφαρμογή**, ποτέ τα δεδομένα του σταθμού. Αν μέσα
// του βρεθεί φάκελος βάσης, εικόνων ή καταγραφών, η εγκατάσταση θα τον
// ξεπακετάριζε πάνω στα πραγματικά αρχεία — και η δουλειά κάποιου θα σβηνόταν
// από μια ενημέρωση.
//
// Ο κανόνας ζει εδώ γιατί τον ρωτούν **δύο** πύλες σε δύο διαφορετικές
// στιγμές: η δημοσίευση (ώστε να μη φτιαχτεί ποτέ τέτοιο πακέτο) και η
// εγκατάσταση (ώστε να μην εγκατασταθεί, αν κάπως φτιάχτηκε). Όσο η λίστα
// ήταν γραμμένη δύο φορές, ένας φάκελος που θα προστίθετο στη μία θα έλειπε
// από την άλλη — και η ασυμφωνία θα φαινόταν μόνο όταν ένα πακέτο περνούσε τη
// δημοσίευση για να κοπεί στην εγκατάσταση.

/// Οι φάκελοι δεδομένων χρήστη που δεν επιτρέπεται να υπάρχουν σε πακέτο.
///
/// Η κατάληξη `/` είναι σκόπιμη: το πρόθεμα είναι **φάκελος**, ώστε ένα αρχείο
/// με όνομα `images_readme.txt` να μη μοιάζει με τον φάκελο `images/`.
const List<String> updatePackageForbiddenPrefixes = [
  'Data Base/',
  'images/',
  'maps_images/',
  'dictionaries/',
  'logs/',
];

/// Πετάει αν έστω μία από τις [entryNames] πατά σε φάκελο δεδομένων χρήστη.
///
/// Πετάει αντί να επιστρέφει το ένοχο όνομα: και οι δύο πύλες αντιδρούν
/// όλα-ή-τίποτα, και ένα API που επέστρεφε τιμή θα επέτρεπε στον επόμενο
/// καλούντα να ξεχάσει να την κοιτάξει.
void assertNoUserDataEntries(Iterable<String> entryNames) {
  for (final raw in entryNames) {
    final name = raw.replaceAll('\\', '/');
    for (final prefix in updatePackageForbiddenPrefixes) {
      final asFolder = prefix.substring(0, prefix.length - 1);
      if (name == asFolder ||
          name.startsWith(prefix) ||
          name.contains('/$prefix')) {
        throw StateError(
          'Το πακέτο περιέχει απαγορευμένη εγγραφή δεδομένων χρήστη: $name',
        );
      }
    }
  }
}
