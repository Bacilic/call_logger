/// Το «επίπεδο» μιας έκδοσης — ο αριθμός που δείχνει το παράσημο αναβάθμισης.
///
/// Οι εκδόσεις της εφαρμογής είναι `major.minor.patch`. Αυτό που ανεβαίνει σε
/// κάθε ουσιαστική δημοσίευση είναι το **minor**, οπότε αυτό είναι το επίπεδο:
/// η `0.34.0` είναι «επίπεδο 34». Το patch (`0.34.1`) είναι διόρθωση της ίδιας
/// δουλειάς — δεν ανεβάζει επίπεδο, όπως δεν ανεβάζει και αριθμό έκδοσης στο
/// ιστορικό.
///
/// Όταν κάποτε το major φύγει από το μηδέν, σκέτο το minor θα ήταν
/// παραπλανητικό (η `1.0.0` θα έδειχνε «0» μετά την `0.41.0`). Τότε το επίπεδο
/// γίνεται `major.minor` — «1.0», «1.4» — που εξακολουθεί να ανεβαίνει.
library;

/// Ο αριθμός επιπέδου για προβολή, π.χ. `0.34.0` → «34», `1.4.2` → «1.4».
///
/// Ό,τι δεν αναγνωρίζεται επιστρέφεται αυτούσιο: η ετικέτα έρχεται από αρχείο
/// έκδοσης που μπορεί να γραφτεί λάθος, και ένα παράξενο κείμενο στο παράσημο
/// είναι πιο χρήσιμο από ένα κενό.
String versionLevelLabel(String version) {
  final match = RegExp(r'^(\d+)\.(\d+)').firstMatch(version.trim());
  if (match == null) return version.trim();

  final major = int.parse(match[1]!);
  final minor = int.parse(match[2]!);
  return major == 0 ? '$minor' : '$major.$minor';
}

/// Μέγεθος γραμματοσειράς που κρατά την ετικέτα επιπέδου μέσα στο παράσημο.
///
/// Το παράσημο έχει σταθερό μέγεθος· ο αριθμός μεγαλώνει με τον καιρό («9» →
/// «34» → «1.12»). Αντί να ξεχειλίσει ή να συρρικνωθεί αυτόματα σε δυσανάγνωστο
/// μέγεθος, η κλίμακα ορίζεται ρητά ανά πλήθος χαρακτήρων.
double versionLevelFontSize(String levelLabel) {
  final length = levelLabel.runes.length;
  if (length <= 2) return 30;
  if (length == 3) return 25;
  if (length == 4) return 20;
  return 16;
}
