/// Γραμμή ιστορικού γίνεται μόνο ό,τι είναι πράγματι κείμενο με περιεχόμενο.
///
/// Οι κάρτες 0.1.0 έως 0.8.2 του `assets/changelog.json` έχουν
/// `"improvements": [null]`. Το `null.toString()` δίνει το **κείμενο** «null» —
/// τεσσάρων χαρακτήρων, άρα περνούσε κάθε φίλτρο «πέτα τα κενά» και φαινόταν
/// στην οθόνη ως κανονική γραμμή μικροβελτίωσης.
///
/// Ένα σημείο για όλους τους καλούντες: και η ανάγνωση για την οθόνη και η
/// σφράγιση έκδοσης περνούν από εδώ, ώστε να μην μπορούν να αποκλίνουν.
List<String> changelogTextLines(dynamic raw) {
  if (raw is! List) return const [];
  return raw.whereType<String>().where((s) => s.trim().isNotEmpty).toList();
}
