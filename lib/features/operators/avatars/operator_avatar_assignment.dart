/// Ποιος κρατά ποιο εικονίδιο, και ποιο δίνεται στον επόμενο.
///
/// **Το συμβόλαιο:** δύο **ενεργά** προφίλ της ίδιας βάσης δεν κρατούν ποτέ το
/// ίδιο εικονίδιο.
///
/// Η λέξη «ενεργά» είναι η καρδιά του κανόνα και είναι απόφαση του Διευθυντή:
/// ο απενεργοποιημένος χρήστης **κρατά** το εικονίδιό του και συνεχίζει να
/// φαίνεται με αυτό, αλλά δεν το δεσμεύει — αν χρειαστεί, δίνεται σε κάποιον
/// που δουλεύει. Η απενεργοποίηση σταματά τη νέα δουλειά, δεν σβήνει την
/// ταυτότητα.

