/// Διαλέγει εικονίδιο για νέο προφίλ· `null` όταν έχουν πιαστεί όλα.
///
/// **Το `null` είναι σχεδιασμός, όχι αποτυχία** (απόφαση Διευθυντή): από τον
/// δέκατο όγδοο ταυτόχρονο χρήστη και μετά, το προφίλ δείχνει το κλασικό
/// ανθρωπάκι μέχρι να προστεθούν κι άλλα εικονίδια. Καμία προειδοποίηση, κανένα
/// εμπόδιο στη δημιουργία — το εικονίδιο είναι στολίδι, όχι προϋπόθεση.
///
/// Η επιλογή είναι **τυχαία** ανάμεσα στα ελεύθερα και όχι «το πρώτο της
/// σειράς»: αλλιώς οι τρεις πρώτοι συνάδελφοι κάθε βάσης θα έπαιρναν πάντα τα
/// ίδια τρία, και το εικονίδιο θα σταματούσε να λέει κάτι για το πρόσωπο.
String? pickAvatarKey(Set<String> taken, {Random? random}) {
  final free = freeAvatars(taken);
  if (free.isEmpty) return null;
  return free[(random ?? Random()).nextInt(free.length)].key;
}
