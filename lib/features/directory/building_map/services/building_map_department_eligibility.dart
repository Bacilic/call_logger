import '../../models/department_model.dart';

/// **Μοναδικό σημείο επιβολής**: ποια τμήματα δικαιούνται θέση στην κάτοψη.
///
/// Ο χάρτης δείχνει τα κτίρια του νοσοκομείου. Μια εξωτερική εταιρεία
/// (DataMed, Agfa) ή μια εξωτερική μονάδα (Κέντρο Υγείας) κουβαλά ανθρώπους και
/// τηλέφωνα σαν τμήμα, αλλά δεν βρίσκεται μέσα σε δικό μας κτίριο — δεν έχει
/// θέση να δείξει, και δεν πρέπει να εμφανίζεται ούτε ως «ατοποθέτητη».
///
/// Κάθε ροή του χάρτη περνά από **εδώ** αντί να φιλτράρει μόνη της. Το
/// διαγραμμένο τμήμα κόβεται στο ίδιο σημείο, ώστε καμία ροή να μη χρειάζεται
/// να θυμάται δύο ξεχωριστούς κανόνες.
List<DepartmentModel> departmentsEligibleForBuildingMap(
  Iterable<DepartmentModel> departments,
) {
  return departments
      .where((d) => !d.isDeleted && d.kind.belongsOnBuildingMap)
      .toList(growable: false);
}
