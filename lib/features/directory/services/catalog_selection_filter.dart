/// Το φίλτρο «δείξε μόνο τα επιλεγμένα» — ένας κανόνας για κάθε καρτέλα του
/// Καταλόγου.
///
/// **Γιατί ζει σε ένα σημείο:** οι τέσσερις καρτέλες (Υπάλληλοι, Τμήματα,
/// Εξοπλισμός, Κατηγορίες) έχουν η καθεμιά το δικό της φιλτράρισμα, με
/// διαφορετικά μοντέλα και διαφορετικές στήλες ταξινόμησης. Αν ο κανόνας
/// γραφόταν τέσσερις φορές, η πέμπτη λίστα που θα αποκτούσε πολλαπλή επιλογή
/// θα τον ξέχναγε — και οι τέσσερις υπάρχουσες θα άρχιζαν να αποκλίνουν στη
/// λεπτομέρεια που μετράει: τι γίνεται όταν αδειάσει η επιλογή.
library;

/// Μένει το φίλτρο ενεργό;
///
/// **Σβήνει μόνο του μόλις αδειάσει η επιλογή.** Αλλιώς ο χρήστης θα έμενε με
/// άδεια λίστα και έναν διακόπτη που δεν θυμάται ότι πάτησε — και θα νόμιζε
/// ότι άδειασε ο κατάλογος.
bool catalogSelectionFilterStaysOn({
  required bool requested,
  required Set<int> selectedIds,
}) {
  return requested && selectedIds.isNotEmpty;
}

/// Κρατά μόνο τις γραμμές που είναι επιλεγμένες, όταν το φίλτρο είναι ενεργό.
///
/// Εφαρμόζεται **μετά** την αναζήτηση: το αποτέλεσμα είναι η τομή των δύο, ώστε
/// «τα επιλεγμένα» να σημαίνει πάντα «μέσα σε ό,τι βλέπεις τώρα».
List<T> applyCatalogSelectionFilter<T>(
  List<T> rows, {
  required bool active,
  required Set<int> selectedIds,
  required int? Function(T row) idOf,
}) {
  if (!active || selectedIds.isEmpty) return rows;
  return rows.where((row) {
    final id = idOf(row);
    return id != null && selectedIds.contains(id);
  }).toList();
}
