import '../../../core/models/app_permission.dart';

/// Πού διορθώνεται μια ρυθμισμένη διαδρομή που δεν βρέθηκε.
///
/// Ο κατάλογος κρατά **μαζί** τον προορισμό και τα λόγια που διαβάζει ο
/// χρήστης, ώστε η οδηγία να μην μπορεί να δείχνει αλλού από εκεί που πάει το
/// κουμπί. Όσο η οδηγία ήταν ελεύθερο κείμενο δίπλα στην καταχώρηση, έστελνε
/// για τα απομακρυσμένα εργαλεία στις «Ρυθμίσεις» — οθόνη που δεν φιλοξενεί
/// ποτέ τη ρύθμιση αυτή.
///
/// Η [requiredPermission] λέει ποιο δικαίωμα χρειάζεται για να έχει νόημα η
/// μετάβαση: χωρίς αυτό ο χρήστης θα έφτανε σε οθόνη όπου το πεδίο είναι
/// κρυμμένο, και το κουμπί θα είχε υποσχεθεί κάτι ανύπαρκτο.
enum PathFixDestination {
  /// Διάλογος «Ρυθμίσεις βάσης δεδομένων», καρτέλα «Αντίγραφα ασφαλείας».
  backupSettings(
    label: 'Βάση Δεδομένων → Ρυθμίσεις βάσης → Αντίγραφα ασφαλείας',
  ),

  /// Ζει στο ίδιο hub με τον έλεγχο — μία κάρτα παραδίπλα.
  remoteTools(label: 'Κατάλογος → Διάφορα → Απομακρυσμένα Εργαλεία'),

  updateFolder(
    label: 'Ρυθμίσεις → Ενημερώσεις',
    requiredPermission: AppPermission.manageUpdateFolder,
  ),

  /// Ο διάλογος ⚙ του Λεξικού — κρατά και την πηγή και την εξαγωγή.
  dictionaryPaths(label: 'Λεξικό → Ρυθμίσεις λεξικού → διαδρομές αρχείων');

  const PathFixDestination({required this.label, this.requiredPermission});

  /// Πώς περιγράφεται στον χρήστη — με τα λόγια που βλέπει στα κουμπιά.
  final String label;

  /// `null` = η μετάβαση είναι πάντα διαθέσιμη.
  final AppPermission? requiredPermission;
}
