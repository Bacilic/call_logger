/// Η αποτυχία μιας εγγραφής κατάστασης Lansweeper — **με την αιτία της**.
///
/// Υπάρχει επειδή η αιτία χανόταν: η εγγραφή έπιανε το σφάλμα, το άφηνε στην
/// κατάσταση του provider (που κανείς δεν διαβάζει για σφάλματα) και γύριζε
/// ένα σκέτο «όχι». Από εκεί και πέρα καμία οθόνη δεν μπορούσε να πει γιατί —
/// η Αναφορά έλεγε «η εγγραφή δεν ολοκληρώθηκε» και το Ιστορικό δεν έλεγε
/// τίποτα απολύτως.
///
/// Τα δύο κείμενα είναι χωριστά επίτηδες, όπως και στην αποτυχία υποβολής μέσω
/// API: το [message] είναι η πρόταση που διαβάζει ο χειριστής, το [report] ό,τι
/// αντιγράφει και στέλνει όταν χρειαστεί διάγνωση.
class LansweeperWriteFailure implements Exception {
  const LansweeperWriteFailure({required this.message, required this.report});

  /// Τι πήγε στραβά, σε ανθρώπινα ελληνικά.
  final String message;

  /// Η τεχνική αναφορά προς αντιγραφή.
  final String report;

  @override
  String toString() => 'LansweeperWriteFailure: $message';
}
