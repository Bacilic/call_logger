import '../../models/call_model.dart';

/// Τι διαβάζει ο χειριστής σε **μία** γραμμή του πρόσφατου ιστορικού.
///
/// **Ο τίτλος κερδίζει όταν υπάρχει.** Οι περιγραφές που έχουν περάσει από την
/// ΤΝ ξεκινούν συνήθως με «Το τμήμα Χ αναφέρει ότι…» — μισή γραμμή για να πει
/// το τμήμα, που ο αναγνώστης ήδη ξέρει επειδή κοιτά την καρτέλα αυτού του
/// ανθρώπου. Ο τίτλος είναι η περίληψη που έγραψε η ΤΝ ή ο ίδιος ο χειριστής
/// στη φόρμα του Lansweeper.
///
/// **Χωρίς τίτλο, τίποτα δεν αλλάζει.** Οι παλιές κλήσεις — και όσες δεν
/// πέρασαν ποτέ από τη φόρμα — δείχνουν την Περιγραφή, όπως πάντα.
String recentCallLineText(CallModel call) {
  final title = (call.title ?? '').trim();
  if (title.isNotEmpty) return title;
  final issue = (call.issue ?? '').trim();
  return issue.isEmpty ? '—' : issue;
}

/// Το πλήρες κείμενο της υπόδειξης: πρόβλημα και λύση, με ετικέτες.
///
/// **Γιατί με ετικέτες:** χωρίς αυτές, δύο παράγραφοι κολλημένες διαβάζονται ως
/// μία και ο αναγνώστης δεν ξέρει πού τελειώνει το πρόβλημα και πού αρχίζει η
/// λύση. Η λύση δεν φαινόταν ποτέ πουθενά στη λίστα, παρότι είναι γραμμένη στις
/// μισές κλήσεις.
///
/// Κενό σημαίνει «δεν υπάρχει τίποτα παραπάνω να δείξω» — τότε η γραμμή δεν
/// χρειάζεται υπόδειξη καθόλου.
String recentCallTooltipText(CallModel call) {
  final issue = (call.issue ?? '').trim();
  final solution = (call.solution ?? '').trim();
  final line = recentCallLineText(call);

  final parts = <String>[];
  // Ό,τι δείχνει ήδη η γραμμή δεν επαναλαμβάνεται στην υπόδειξη: θα ήταν ο ίδιος
  // θόρυβος, μία γραμμή πιο κάτω.
  if (issue.isNotEmpty && issue != line) parts.add('Πρόβλημα: $issue');
  if (solution.isNotEmpty) parts.add('Λύση: $solution');
  return parts.join('\n\n');
}
